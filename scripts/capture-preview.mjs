import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'docs/images');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto(process.env.STASH_REVIEW_PREVIEW_URL || 'http://127.0.0.1:4173/');
  await page.getByRole('button', { name: 'Open stash Ambient note capture', exact: true }).click();
  await page.locator('[data-file-path="src/capture.ts"] .sr-code').first().waitFor();
  await page.screenshot({ path: resolve(output, 'stash-review-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Single file', exact: true }).click();
  await page.getByRole('tree', { name: 'Changed files', exact: true }).locator('[data-tree-path="src/capture.ts"]').click();
  await page.waitForTimeout(350);
  await page.locator('.sr-diff-scroll').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: resolve(output, 'stash-review-focused.png'), fullPage: true });
  await page.getByRole('button', { name: 'Split diff', exact: true }).click();
  await page.locator('.sr-split-row').first().waitFor();
  await page.locator('.sr-diff-scroll').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: resolve(output, 'stash-review-split.png'), fullPage: true });
  await page.getByRole('button', { name: 'Unified diff', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Filter changed files', exact: true }).fill('format.ts');
  await page.getByRole('tree', { name: 'Changed files', exact: true }).locator('[data-tree-path="src/capture/format.ts"]').click();
  await page.waitForTimeout(350);
  await page.screenshot({ path: resolve(output, 'stash-review-tree.png'), fullPage: true });
  await page.getByRole('searchbox', { name: 'Filter changed files', exact: true }).fill('');
  await page.getByRole('tree', { name: 'Changed files', exact: true }).locator('[data-tree-path="src/capture.ts"]').click();
  await page.waitForTimeout(350);
  await page.getByRole('button', { name: 'All files', exact: true }).click();
  await page.locator('.sr-diff-scroll').evaluate(element => { element.scrollTop = 0; });
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
  await page.locator('body.theme-light').waitFor();
  await page.screenshot({ path: resolve(output, 'stash-review-light.png'), fullPage: true });
  await page.setViewportSize({ width: 430, height: 932 });
  await page.getByRole('button', { name: 'Single file', exact: true }).click();
  await page.screenshot({ path: resolve(output, 'stash-review-narrow.png'), fullPage: true });
  console.log('Updated dark, light, focused, split, filtered tree, and narrow screenshots from fictional demo data.');
} finally { await browser.close(); }
